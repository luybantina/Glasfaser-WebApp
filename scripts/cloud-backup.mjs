import {mkdir,writeFile} from 'node:fs/promises';
import {resolve,dirname,relative} from 'node:path';
import {createHash} from 'node:crypto';
import {options,config,run,rows,root} from './cloud-cli.mjs';
import {unpack} from '../cloud/shared.mjs';
const opts=options(),source=resolve(root,opts.config||'wrangler.jsonc');
const dest=resolve(root,opts.output||`.private/backup-${new Date().toISOString().replace(/[:.]/g,'-')}.gfb`);
if(!relative(root,dest).startsWith('.private'+(process.platform==='win32'?'\\':'/')))throw new Error('Backups must be written inside .private/');
const cfg=await config(source),database=cfg.d1_databases.find(x=>x.binding==='DB');
const result=rows(run(['d1','execute',database.database_name,'--config',source,'--remote','--command','SELECT collection,id,payload,(SELECT revision FROM meta WHERE id=1) AS revision FROM records ORDER BY rowid','--json'],{capture:true}));
if(!result.length)throw new Error('Refusing to export an empty database');
const data=unpack(result);
const backup={format:'GFB-1',appVersion:'43.1',createdAt:new Date().toISOString(),reason:'cloud-migration',data};
const contents=JSON.stringify(backup,null,2)+'\n';
await mkdir(dirname(dest),{recursive:true,mode:0o700});
await writeFile(dest,contents,{mode:0o600,flag:'wx'});
const manifest={createdAt:backup.createdAt,source:{account_id:cfg.account_id,database_id:database.database_id,revision:result[0].revision},sha256:createHash('sha256').update(contents).digest('hex'),totalRecords:result.length,counts:Object.fromEntries(Object.entries(data).map(([key,value])=>[key,Array.isArray(value)?value.length:1]))};
await writeFile(dest+'.manifest.json',JSON.stringify(manifest,null,2)+'\n',{mode:0o600,flag:'wx'});
console.log(`Saved ${result.length} application records to ${dest}. Includes password hashes; excludes sessions and Cloudflare credentials.`);
