import {readFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {options,config,run,rows,root} from './cloud-cli.mjs';
const opts=options();
if(!opts.backup)throw new Error('Provide --backup .private/path/database.gfb');
const targetPath=join(root,opts.config||'wrangler.migration.json');
const [target,production]=await Promise.all([config(targetPath),config(join(root,'wrangler.jsonc'))]);
const db=target.d1_databases.find(x=>x.binding==='DB');
if(db.database_id===production.d1_databases[0].database_id)throw new Error('Refusing to import into the current production database');
if(opts.config&&opts.config!=='wrangler.migration.json'&&db.database_id===(await config(join(root,'wrangler.migration.json'))).d1_databases[0].database_id)throw new Error('Refusing to import into the live database');
const backupPath=resolve(root,opts.backup),raw=await readFile(backupPath);
const manifest=JSON.parse(await readFile(backupPath+'.manifest.json','utf8'));
if(createHash('sha256').update(raw).digest('hex')!==manifest.sha256)throw new Error('Backup SHA-256 mismatch');
const before=rows(run(['d1','execute',db.database_name,'--config',targetPath,'--remote','--command','SELECT count(*) AS total FROM records','--json'],{capture:true}));
if(before[0]?.total!==0)throw new Error('Destination is not empty; refusing to replace existing data');
execFileSync(process.execPath,['scripts/prepare-import.mjs',backupPath],{cwd:root,stdio:'inherit'});
run(['d1','execute',db.database_name,'--config',targetPath,'--remote','--file',join(root,'.private/seed.sql')]);
const after=rows(run(['d1','execute',db.database_name,'--config',targetPath,'--remote','--command','SELECT collection,id,payload FROM records ORDER BY rowid','--json'],{capture:true}));
const {unpack}=await import('../cloud/shared.mjs');
const {isDeepStrictEqual}=await import('node:util');
if(after.length!==manifest.totalRecords||!isDeepStrictEqual(unpack(after),JSON.parse(raw).data))throw new Error('Restored data does not exactly match the backup; do not switch users yet');
console.log(`Verified all ${after.length} restored records, including credentials. Build and deploy using the migration config next.`);
